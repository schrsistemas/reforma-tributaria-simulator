BEGIN;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fiscal_hub_app') THEN
    CREATE ROLE fiscal_hub_app
      LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
END
$$;

GRANT USAGE ON SCHEMA fiscal TO fiscal_hub_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA fiscal TO fiscal_hub_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA fiscal
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO fiscal_hub_app;
COMMIT;
